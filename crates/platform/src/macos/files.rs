//! Files and the clipboard: a file's icon, the pasteboard (read / write), the Trash, the share menu, and dragging
//! files out of a window.
use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2::{define_class, msg_send, AllocAnyThread, DefinedClass, MainThreadMarker, MainThreadOnly};
use std::cell::RefCell;
use objc2_app_kit::{
    NSApplication, NSBitmapImageFileType, NSBitmapImageRep, NSDragOperation, NSDraggingContext, NSDraggingItem, NSDraggingSession,
    NSDraggingSource, NSImage, NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
    NSSharingServicePicker, NSView, NSWorkspace,
};
use objc2_foundation::{NSArray, NSData, NSDictionary, NSFileManager, NSObject, NSObjectProtocol, NSPoint, NSRect, NSRectEdge, NSSize, NSString, NSURL};

fn png_of(image: &NSImage, px: f64) -> Option<Vec<u8>> {
    let mut rect = NSRect::new(NSPoint::new(0.0, 0.0), NSSize::new(px, px));
    let cg = unsafe { image.CGImageForProposedRect_context_hints(&mut rect, None, None) }?;
    let rep = NSBitmapImageRep::initWithCGImage(NSBitmapImageRep::alloc(), &cg);
    let png = unsafe { rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new()) }?;
    Some(png.to_vec())
}

/// A file's or app's icon as Finder shows it, a PNG about `px` wide.
pub fn icon_png(path: &str, px: f64) -> Option<Vec<u8>> {
    objc2::rc::autoreleasepool(|_| png_of(&NSWorkspace::sharedWorkspace().iconForFile(&NSString::from_str(path)), px))
}

/// The pasteboard's change count (it goes up with each copy, in any app).
pub fn change_count() -> isize {
    objc2::rc::autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount())
}

/// What's on the clipboard now.
pub enum Clip {
    /// a copy marked private / passing / made by an app (password managers), or files copied in Finder
    Skip,
    Text(String),
    /// PNG bytes
    Image(Vec<u8>),
    None,
}

pub fn read_clip() -> Clip {
    objc2::rc::autoreleasepool(|_| {
        let pb = NSPasteboard::generalPasteboard();
        let types: Vec<String> = pb.types().map(|t| t.iter().map(|s| s.to_string()).collect()).unwrap_or_default();
        let skip = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url", "com.agilebits.onepassword"];
        if types.iter().any(|t| skip.contains(&t.as_str())) {
            return Clip::Skip;
        }
        let has = |t: &NSString| types.iter().any(|x| *x == t.to_string());
        unsafe {
            if has(NSPasteboardTypeString) {
                if let Some(s) = pb.stringForType(NSPasteboardTypeString) {
                    return Clip::Text(s.to_string());
                }
            }
            if has(NSPasteboardTypePNG) {
                if let Some(d) = pb.dataForType(NSPasteboardTypePNG) {
                    return Clip::Image(d.to_vec());
                }
            }
            if has(NSPasteboardTypeTIFF) {
                if let Some(d) = pb.dataForType(NSPasteboardTypeTIFF) {
                    let rep = NSBitmapImageRep::initWithData(NSBitmapImageRep::alloc(), &d);
                    if let Some(png) = rep.and_then(|r| r.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new())) {
                        return Clip::Image(png.to_vec());
                    }
                }
            }
        }
        Clip::None
    })
}

pub fn write_text(text: &str) -> bool {
    objc2::rc::autoreleasepool(|_| {
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
    })
}

pub fn write_png(png: &[u8]) -> bool {
    objc2::rc::autoreleasepool(|_| {
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        pb.setData_forType(Some(&NSData::with_bytes(png)), unsafe { NSPasteboardTypePNG })
    })
}

/// The Downloads folder (`~/Downloads`).
pub fn downloads() -> std::path::PathBuf {
    std::path::PathBuf::from(std::env::var("HOME").unwrap_or_default()).join("Downloads")
}

/// Into the Trash (Finder's Put Back works).
pub fn trash(path: &str) -> Result<(), String> {
    objc2::rc::autoreleasepool(|_| {
        let url = NSURL::fileURLWithPath(&NSString::from_str(path));
        NSFileManager::defaultManager().trashItemAtURL_resultingItemURL_error(&url, None).map_err(|e| e.localizedDescription().to_string())
    })
}

/// A picture converted to JPEG (`jpeg`) or PNG at `dst` (`sips`).
pub fn convert_picture(src: &str, dst: &std::path::Path, jpeg: bool) -> Result<(), String> {
    let o = std::process::Command::new("/usr/bin/sips").args(["-s", "format", if jpeg { "jpeg" } else { "png" }, src, "--out"]).arg(dst)
        .output().map_err(|e| e.to_string())?;
    if o.status.success() { Ok(()) } else { Err(String::from_utf8_lossy(&o.stderr).trim().lines().last().unwrap_or("failed").to_string()) }
}

/// Ejects a drive (`diskutil eject`); `root` is its folder, `/Volumes/Name`.
pub fn eject(root: &str) -> Result<(), String> {
    let o = std::process::Command::new("/usr/sbin/diskutil").arg("eject").arg(root).output().map_err(|e| e.to_string())?;
    if o.status.success() { Ok(()) } else { Err(String::from_utf8_lossy(&o.stderr).trim().lines().last().unwrap_or("failed").to_string()) }
}

/// Whether `path` is a drive that `eject` takes: a volume's own folder, `/Volumes/Name`.
pub fn is_drive(path: &str) -> bool {
    path.starts_with("/Volumes/") && path.trim_end_matches('/').matches('/').count() == 2
}

fn urls(paths: &[String]) -> Retained<NSArray<NSURL>> {
    let v: Vec<Retained<NSURL>> = paths.iter().map(|p| NSURL::fileURLWithPath(&NSString::from_str(p))).collect();
    NSArray::from_retained_slice(&v)
}

thread_local! {
    static LAST_PICKER: RefCell<Option<Retained<NSSharingServicePicker>>> = const { RefCell::new(None) };
    static LAST_DRAG_SOURCE: RefCell<Option<Retained<DragSource>>> = const { RefCell::new(None) };
}

/// The macOS share menu (AirDrop, Mail, Messages…) for these files, at the mouse. Main thread; `view` is an
/// `NSView*`.
///
/// # Safety
/// `view` must be a live NSView.
pub unsafe fn share(view: *mut std::ffi::c_void, paths: &[String]) {
    if MainThreadMarker::new().is_none() {
        return;
    }
    let Some(view) = (unsafe { (view as *const NSView).as_ref() }) else { return };
    let Some(win) = view.window() else { return };
    let items = urls(paths);
    let picker = unsafe { NSSharingServicePicker::initWithItems(NSSharingServicePicker::alloc(), &*(&*items as *const NSArray<NSURL> as *const NSArray)) };
    let at = view.convertPoint_fromView(win.mouseLocationOutsideOfEventStream(), None);
    picker.showRelativeToRect_ofView_preferredEdge(NSRect::new(NSPoint::new(at.x - 1.0, at.y - 1.0), NSSize::new(2.0, 2.0)), view, NSRectEdge::MinY);
    // Keep only the active picker alive on the main thread; opening the next releases the previous one.
    LAST_PICKER.with(|slot| *slot.borrow_mut() = Some(picker));
}

/// Why the last `share` didn't open (as on Windows): the share menu has no way to fail that it tells, so None.
pub fn share_failed() -> Option<String> {
    None
}

pub struct DragIvars {
    done: Box<dyn Fn(bool)>,
}

define_class!(
    #[unsafe(super(NSObject))]
    #[thread_kind = MainThreadOnly]
    #[name = "SymponyDragSource"]
    #[ivars = DragIvars]
    struct DragSource;

    unsafe impl NSObjectProtocol for DragSource {}

    unsafe impl NSDraggingSource for DragSource {
        #[unsafe(method(draggingSession:sourceOperationMaskForDraggingContext:))]
        fn mask(&self, _s: &NSDraggingSession, c: NSDraggingContext) -> NSDragOperation {
            // (never into Sympony itself; outside, a copy or a link: the Shelf only points at files, a drag never
            // moves the user's file away)
            if c == NSDraggingContext::WithinApplication { NSDragOperation::None } else { NSDragOperation::Copy | NSDragOperation::Link }
        }

        #[unsafe(method(draggingSession:endedAtPoint:operation:))]
        fn ended(&self, _s: &NSDraggingSession, _p: NSPoint, op: NSDragOperation) {
            (self.ivars().done)(op != NSDragOperation::None);
        }
    }
);

/// Drags these files out of `view` from the mouse's place now (the drag the web page just started); `done(dropped)`
/// when it ends. Main thread, during a mouse drag.
///
/// # Safety
/// `view` must be a live NSView.
pub unsafe fn drag_out(view: *mut std::ffi::c_void, paths: &[String], done: Box<dyn Fn(bool)>) -> bool {
    let Some(mtm) = MainThreadMarker::new() else { return false };
    let Some(view) = (unsafe { (view as *const NSView).as_ref() }) else { return false };
    let Some(event) = NSApplication::sharedApplication(mtm).currentEvent() else { return false };
    // only from the page's own mouse drag, still going on in this window (else AppKit may throw, or the image sticks)
    use objc2_app_kit::{NSEvent, NSEventType};
    let mouse = matches!(event.r#type(), NSEventType::LeftMouseDown | NSEventType::LeftMouseDragged);
    let here = event.window(mtm).zip(view.window()).is_some_and(|(a, b)| std::ptr::eq(&*a, &*b));
    if !mouse || !here || NSEvent::pressedMouseButtons() & 1 == 0 {
        return false;
    }
    let at = view.convertPoint_fromView(event.locationInWindow(), None);
    let items: Vec<Retained<NSDraggingItem>> = paths.iter().map(|p| {
        let url = NSURL::fileURLWithPath(&NSString::from_str(p));
        let item = NSDraggingItem::initWithPasteboardWriter(NSDraggingItem::alloc(), ProtocolObject::from_ref(&*url));
        let icon = NSWorkspace::sharedWorkspace().iconForFile(&NSString::from_str(p));
        unsafe { item.setDraggingFrame_contents(NSRect::new(NSPoint::new(at.x - 24.0, at.y - 24.0), NSSize::new(48.0, 48.0)), Some(&icon)) };
        item
    }).collect();
    if items.is_empty() {
        return false;
    }
    let source = DragSource::alloc(mtm).set_ivars(DragIvars { done });
    let source: Retained<DragSource> = unsafe { msg_send![super(source), init] };
    view.beginDraggingSessionWithItems_event_source(&NSArray::from_retained_slice(&items), &event, ProtocolObject::from_ref(&*source));
    // Keep only the current drag source alive on the main thread; the next drag releases the previous one.
    LAST_DRAG_SOURCE.with(|slot| *slot.borrow_mut() = Some(source));
    true
}

/// `osascript` choosing files / a folder / an app / an audio file: their POSIX paths (none: cancelled). `what`:
/// "files" (several), "folder", "app", "backup" (from Downloads), "audio", anything else one file (from Applications).
pub fn choose(what: &str, prompt: &str) -> Vec<String> {
    let script = match what {
        "files" => format!("set l to choose file with prompt {prompt:?} with multiple selections allowed\nset o to \"\"\nrepeat with f in l\nset o to o & POSIX path of f & linefeed\nend repeat\nreturn o"),
        "folder" => format!("POSIX path of (choose folder with prompt {prompt:?})"),
        "app" => format!("POSIX path of (choose application with prompt {prompt:?} as alias)"),
        "backup" => format!("POSIX path of (choose file with prompt {prompt:?} default location (path to downloads folder))"),
        "audio" => format!("POSIX path of (choose file with prompt {prompt:?} of type {{\"public.audio\"}})"),
        _ => format!("POSIX path of (choose file with prompt {prompt:?} default location (path to applications folder))"),
    };
    let Ok(out) = std::process::Command::new("/usr/bin/osascript").args(["-e", &script]).output() else { return vec![] };
    if !out.status.success() {
        return vec![];
    }
    String::from_utf8_lossy(&out.stdout).lines().map(|l| l.trim().to_string()).filter(|l| !l.is_empty()).collect()
}
